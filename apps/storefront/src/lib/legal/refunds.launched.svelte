	<h1>Refund Policy</h1>

	<p>Nothing here limits rights you have under the consumer law where you live.</p>

	<h2>One-off reports</h2>
	<p>If the report fails or isn't what we described, ask within 14 days and we refund it in full. EU/UK buyers keep their legal withdrawal rights.</p>

	<h2>Subscriptions</h2>
	<p>Every plan renews automatically each month until you cancel. You can cancel at any time on the Subscription Management page of your Starhold Account. You choose how to end a plan, and there are no cancellation fees. Cancelling and deleting your account are two separate actions.</p>

	<h3>Cancel</h3>
	<p>Cancel stops renewal. Your account and your data stay. You choose:</p>
	<ul>
		<li><strong>Run out the period.</strong> You keep access until the end of the time you paid for.</li>
		<li><strong>Prorated refund now.</strong> We refund the unused part of the period, less the payment processing cost (see below), and access ends.</li>
	</ul>
	<p>If you are in the EU or UK, you may also withdraw from a new subscription within 14 days of buying it. Tell us, and we refund the unused part of the period with nothing held back.</p>

	<h3>Delete your account</h3>
	<p>You can delete your account yourself from the account page. If you cannot, write to <a href="mailto:privacy@starhold.dev">privacy@starhold.dev</a> and we will do it within one month.</p>
	<p>You choose when it happens:</p>
	<ul>
		<li><strong>Delete now.</strong> With no paid plan, your account and data are removed from live systems as soon as you confirm. With a paid plan, they are removed after 24 hours, and we refund the unused time, pro rata, less the payment processing cost.</li>
		<li><strong>Delete at the end of the period.</strong> Access continues and the account shows "deleting on" the date. You can undo it until then. When the period ends, your data is deleted. No refund is needed.</li>
	</ul>
	<p>Every delete asks you to confirm first. Deletion works in three layers: live data is gone when the delete runs, backups drop it within 30 days, and only the bare purchase record (amount, date, provider reference, no content) is kept, as tax law requires, for up to 7 years.</p>

	<h2>The payment processing cost</h2>
	<p>A refund because you changed your mind, on any Starhold product or the Starhold Suite, is paid less the payment processing cost. That is the fee our payment provider kept when you paid, which it does not give back to us when we refund. We hold back only that real cost for that order, nothing else. On a $5 plan it is typically under $1. When the refund is made, we show you what you paid, the cost held back and the amount refunded.</p>
	<p>The refund is in full, with nothing held back, when it is our fault: a billing error, a duplicate charge, or a service we failed to provide. It is also in full when you leave because we made a material change to our terms, and wherever the law where you live gives you a right to a full refund.</p>

	<h2>How refunds are paid</h2>
	<p>The merchant of record (today Polar) is the seller of record and issues refunds; we trigger them for you from our side. Refunds go back to your original payment method through them. Some providers review a refund before they pay it out. While the provider works through it, the status reads "refund issued, provider processing", and it can take several business days to reach you.</p>

	<h2>Billing problems</h2>
	<p>If a charge looks wrong, write to <a href="mailto:hello@starhold.dev">hello@starhold.dev</a> first. We answer billing questions within 5 business days. You always keep your card network's chargeback rights.</p>

